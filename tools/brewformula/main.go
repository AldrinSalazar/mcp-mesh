package main

import (
	"bufio"
	"flag"
	"fmt"
	"io"
	"os"
	"regexp"
	"strings"
	"text/template"
)

// brewformula prints the Homebrew formula for one node release, from the
// release's SHA256SUMS. The release workflow commits it to the tap
// (github.com/<owner>/homebrew-tap, Formula/mcp-mesh-node.rb).
//
//	go run ./tools/brewformula -tag v1.2.3 -repo AldrinSalazar/mcp-mesh dist/SHA256SUMS
func main() {
	tag := flag.String("tag", "", "release tag, e.g. v1.2.3")
	repo := flag.String("repo", "", "GitHub repository, e.g. AldrinSalazar/mcp-mesh")
	flag.Parse()
	if *tag == "" || *repo == "" || flag.NArg() != 1 {
		fmt.Fprintln(os.Stderr, "usage: brewformula -tag TAG -repo OWNER/NAME SHA256SUMS")
		os.Exit(2)
	}
	sums, err := os.Open(flag.Arg(0))
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer sums.Close()
	if err := write(os.Stdout, *tag, *repo, sums); err != nil {
		fmt.Fprintln(os.Stderr, "brewformula:", err)
		os.Exit(1)
	}
}

// Homebrew runs on 64-bit macOS and Linux only.
var targets = []string{"darwin_arm64", "darwin_amd64", "linux_arm64", "linux_amd64"}

var stableTag = regexp.MustCompile(`^v\d+\.\d+\.\d+$`)

func write(w io.Writer, tag, repo string, sums io.Reader) error {
	if !stableTag.MatchString(tag) {
		return fmt.Errorf("tag %q is not a release (vX.Y.Z)", tag)
	}
	checksums := make(map[string]string)
	scanner := bufio.NewScanner(sums)
	for scanner.Scan() {
		// sha256sum writes "<hex>  <name>" ("<hex> *<name>" in binary mode).
		fields := strings.Fields(scanner.Text())
		if len(fields) == 2 {
			checksums[strings.TrimPrefix(fields[1], "*")] = fields[0]
		}
	}
	if err := scanner.Err(); err != nil {
		return fmt.Errorf("read checksums: %w", err)
	}
	assets := make(map[string]asset)
	for _, target := range targets {
		name := "mcp-mesh-node_" + target + ".tar.gz"
		sum := checksums[name]
		if len(sum) != 64 {
			return fmt.Errorf("no checksum for %s", name)
		}
		assets[target] = asset{URL: fmt.Sprintf("https://github.com/%s/releases/download/%s/%s", repo, tag, name), SHA256: sum}
	}
	return formula.Execute(w, map[string]any{"Repo": repo, "Assets": assets})
}

type asset struct{ URL, SHA256 string }

var formula = template.Must(template.New("formula").Parse(`# Generated by tools/brewformula in {{.Repo}} for each release.
class McpMeshNode < Formula
  desc "Shares this machine's MCP servers with an mcp-mesh hub"
  homepage "https://github.com/{{.Repo}}"
  license "PolyForm-Noncommercial-1.0.0"

  on_macos do
    on_arm do
      url "{{.Assets.darwin_arm64.URL}}"
      sha256 "{{.Assets.darwin_arm64.SHA256}}"
    end
    on_intel do
      url "{{.Assets.darwin_amd64.URL}}"
      sha256 "{{.Assets.darwin_amd64.SHA256}}"
    end
  end

  on_linux do
    on_arm do
      url "{{.Assets.linux_arm64.URL}}"
      sha256 "{{.Assets.linux_arm64.SHA256}}"
    end
    on_intel do
      url "{{.Assets.linux_amd64.URL}}"
      sha256 "{{.Assets.linux_amd64.SHA256}}"
    end
  end

  def install
    bin.install "mcp-mesh-node"
  end

  def caveats
    <<~EOS
      Set this machine up with the command the hub's dashboard shows for a
      node key, then run mcp-mesh-node to add MCP servers and start the node.

      After brew upgrade, a running node keeps the old version until it
      restarts:
        mcp-mesh-node stop && mcp-mesh-node start
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/mcp-mesh-node --version")
  end
end
`))
